/// Các kiểu hiển thị turn indicator.
enum TurnIndicatorStyle {
  /// Mũi tên nhấp nhô trên đầu nhân vật (kiểu FF, Dragon Quest)
  bouncingArrow,

  /// Vòng tròn xoay dưới chân (kiểu Pokémon, Persona)
  rotatingRing,

  /// Vòng tròn lan ra rồi thu lại theo nhịp (kiểu MOBA)
  pulseRing,

  /// Hào quang phát sáng quanh nhân vật (kiểu Fire Emblem)
  glowAura,

  /// Cột sáng chiếu xuống từ trên (kiểu Disgaea)
  spotlight,
}
